#!/usr/bin/env node
// 从确认版对照物 mock.html 机械生成 board.html 内的 700×1000 竖屏工作台。
//
// 为什么是生成而不是手抄：AC-006 要求「以 mock.html 为真源」。手抄的副本会随时间与真源
// 漂移，且漂移无人察觉。生成 + 把 mock 的 sha256 写进产物，让「产品是否仍跟着真源」
// 变成 selftest 可机械断言的事实（board-ui 域会核对这个 sha）。
//
// 隔离手段是 Shadow DOM：mock 的 id 与 class 大量与桌面星图重名，两者的 :root 变量与字体
// 栈也不同。shadow root 让 mock 的 CSS 逐字保留（只把 :root 改成 :host）而不污染桌面层，
// 也不产生重复 id —— 桌面全屏星图因此完全不被改动（强约束：desktop 不得降级）。
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const SKILL_DIR = dirname(SCRIPT_DIR);
export const BOARD_PATH = join(SKILL_DIR, 'board.html');
export const DEFAULT_MOCK_PATH = resolve(join(
  SKILL_DIR, '..', '..', '..',
  '.aes-workflow', 'grilling', '2026-08-25-aes-worktree-board-session-evolution', '2-prototype', 'mock.html',
));
export const BEGIN_MARKER = '<!-- PORTRAIT-WORKBENCH:BEGIN';
export const END_MARKER = '<!-- PORTRAIT-WORKBENCH:END -->';

export function sha256Of(buffer) {
  return createHash('sha256').update(buffer).digest('hex').toUpperCase();
}

function section(source, open, close, label) {
  const start = source.indexOf(open);
  const end = source.indexOf(close, start);
  if (start < 0 || end < 0) throw new Error(`mock.html 缺少 ${label} 区段`);
  return source.slice(start + open.length, end);
}

// mock 的全局选择器（html/body/.preview-label）在 shadow root 里匹配不到任何东西，
// 必须换成等价的 :host 规则，否则 700×1000 下的居中与底色会丢失。
function adaptCss(css) {
  const dropped = [
    /html,body \{[^}]*\}\n?/,
    /\n\s*body \{ display:grid; place-items:center; background:#ECE9E0; \}/,
    /\n\s*\.preview-label \{[^}]*\}/,
    /\n\s*\.preview-label strong \{[^}]*\}/,
    /\n\s*@media \(max-width:900px\) \{ \.preview-label \{ display:none; \} \}/,
  ];
  let adapted = css;
  for (const pattern of dropped) {
    if (!pattern.test(adapted)) throw new Error(`mock.html CSS 缺少预期区块: ${pattern}`);
    adapted = adapted.replace(pattern, '');
  }
  if (!adapted.includes(':root {')) throw new Error('mock.html CSS 缺少 :root 变量块');
  adapted = adapted.replace(':root {', ':host {');
  // host 承担原来 html/body 的角色：铺满容器、居中 .app、提供底色与继承字体。
  return `:host {\n      display:grid; place-items:center; width:100%; height:100%;\n      overflow:hidden; background:#ECE9E0; color:var(--ink); font-family:var(--ui);\n    }\n${adapted}`;
}

// 三个 fixture 数组改为「有注入用注入，没有用 mock 原值」。
// 保留 mock 原值是刻意的：截图 diff 时产品与真源必须渲染同一批数据，
// 否则 diff 出来的差异分不清是布局问题还是数据问题。
function adaptScript(script) {
  let adapted = script;
  for (const name of ['issues', 'links', 'runners']) {
    const pattern = new RegExp(`const ${name}\\s*=\\s*\\[`);
    if (!pattern.test(adapted)) throw new Error(`mock.html script 缺少 const ${name}`);
    adapted = adapted.replace(pattern, `const ${name} = (data && data.${name}) || [`);
  }
  return adapted;
}

export function generatePortraitBlock(mockPath = DEFAULT_MOCK_PATH) {
  const raw = readFileSync(mockPath);
  const mockSha = sha256Of(raw);
  const source = raw.toString('utf8');
  const css = adaptCss(section(source, '<style>', '</style>', '<style>'));
  const markup = section(source, '<main class="app booting" id="app">', '</main>', '<main class="app">');
  const script = adaptScript(section(source, '<script>', '</script>', '<script>'));

  return `${BEGIN_MARKER} generated by scripts/build-portrait.mjs from mock.html
     mockSha256=${mockSha}
     700×1000 竖屏工作台。渲染在 shadow root 内，与桌面全屏星图完全隔离。
     不要手改本区段：改 mock 或改生成器，然后重跑 build-portrait.mjs。 -->
<template id="portrait-template"><style>${css}</style><main class="app booting" id="app">${markup}</main></template>
<script>
window.__PORTRAIT_MOCK_SHA256__ = ${JSON.stringify(mockSha)};
// mock 的脚本逐字搬进来，只把 document 换成指向 shadow root 的桥接对象。
// 这样 43 处 getElementById 全部落在 shadow 作用域内，无需逐处改写。
window.__bootPortraitWorkbench__ = function (document, data) {${script}};
</script>
${END_MARKER}`;
}

// 比较与写入都按归一化后的内容进行：board.html 在本仓是 CRLF，生成器输出 LF，
// 若不归一化，换行风格本身会被误报成「产品偏离真源」。
export function normalizeEol(text) {
  return String(text).replaceAll('\r\n', '\n');
}

export function writePortraitBlock({ mockPath = DEFAULT_MOCK_PATH, boardPath = BOARD_PATH } = {}) {
  const block = generatePortraitBlock(mockPath);
  const board = readFileSync(boardPath, 'utf8');
  const start = board.indexOf(BEGIN_MARKER);
  const end = board.indexOf(END_MARKER);
  if (start < 0 || end < 0) throw new Error('board.html 缺少 PORTRAIT-WORKBENCH 标记区段');
  // 跟随目标文件既有的换行风格，避免每次重跑都把整份 board.html 改一遍。
  const crlf = board.includes('\r\n');
  const shaped = crlf ? normalizeEol(block).replaceAll('\n', '\r\n') : normalizeEol(block);
  const next = `${board.slice(0, start)}${shaped}${board.slice(end + END_MARKER.length)}`;
  const changed = next !== board;
  if (changed) writeFileSync(boardPath, next);
  return { changed, mockSha: sha256Of(readFileSync(mockPath)), bytes: shaped.length };
}

if (resolve(process.argv[1] || '') === resolve(fileURLToPath(import.meta.url))) {
  const result = writePortraitBlock();
  console.log(JSON.stringify({ ok: true, ...result }));
}
