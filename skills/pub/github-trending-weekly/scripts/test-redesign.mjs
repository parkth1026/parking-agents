import { readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { buildPayload } from './lib/report-data.mjs';
import { coreImage } from './lib/report-extras.mjs';
import { extractNotes, NICHE_TAGS, classification } from './lib/analysis.mjs';
import { validateWeek } from './lib/validate.mjs';
import { createHash } from 'node:crypto';

export async function runRedesign({check,run,mkws,fixtures}){
 for(const [file,hash] of Object.entries(JSON.parse(readFileSync(join(fixtures,'golden','sha256.json'),'utf8'))))check('黄金尺子 hash '+file,createHash('sha256').update(readFileSync(join(fixtures,'golden',file))).digest('hex')===hash);
 const ws=mkws('redesign'),weeks=join(ws,'data','weeks'),repos=join(ws,'data','repos');
 const golden=JSON.parse(readFileSync(join(fixtures,'golden','2026-W36.json'),'utf8'));
 const analysis=readFileSync(join(fixtures,'golden','2026-W36.analysis.md'),'utf8');
 const writeDoc=doc=>writeFileSync(join(weeks,doc.week+'.json'),JSON.stringify(doc));
 writeDoc(golden);
 copyFileSync(join(fixtures,'golden','2026-W36.analysis.md'),join(weeks,'2026-W36.analysis.md'));
 copyFileSync(join(fixtures,'golden','tt-a1i__archify.history.json'),join(repos,'tt-a1i__archify.json'));
 const w=buildPayload(weeks).weeks[0];
 console.log('== T11/AC-002 SURGE 黄金快照 ==');
 const surge=w.repos.filter(r=>r.stars_week/r.stars_total>=.2).map(r=>r.full_name);
 check('恰 5 仓 ≥20%（黄金数据不重算/不修饰）',JSON.stringify(surge)===JSON.stringify(['tt-a1i/archify','anthropics/claude-plugins-community','cursor/plugins','freestylefly/awesome-gpt-image-2','apache/maka']));
 check('archify ×21.7 vs W28（周增而非总星）',w.repos[0].accel.ratio===21.7&&w.repos[0].accel.baseWeek==='2026-W28');
 check('不足两快照无 accel',!('accel' in w.repos[1]));
 check('TLDR 最猛前三按 velocity',w.repos.slice().sort((a,b)=>b.stars_week/b.stars_total-a.stars_week/a.stars_total).slice(0,3).map(r=>r.full_name).join('|')==='anthropics/claude-plugins-community|tt-a1i/archify|freestylefly/awesome-gpt-image-2');
 console.log('== T12/AC-003 载荷契约 + AC-004 图片 ==');
 check('20 仓四字段完整抽取且标签受控',w.repos.every(r=>r.note&&['positioning','whyNow','trust','niche'].every(k=>typeof r.note[k]==='string')&&Array.isArray(r.note.nicheTags)&&r.note.nicheTags.every(t=>NICHE_TAGS.includes(t))));
 check('新增 readme 上限 2400 且旧字段保留',w.repos[0].readme.length===2400&&w.repos.every(r=>r.readme.length<=2400&&r.readme===r.readme_excerpt)&&'created_at' in w.repos[0]);
 check('字段映射/analysis 整篇内联',w.repos[0].created===golden.repos[0].created_at&&w.repos[0].issues===golden.repos[0].open_issues&&w.analysis===analysis&&w.analyzed);
 check('核心图跳过徽章，解析相对路径',w.repos[0].coreImg==='https://raw.githubusercontent.com/tt-a1i/archify/HEAD/docs/assets/archify-readme-hero.png');
 check('无 README 图不写 coreImg',!('coreImg' in w.repos[1]));
 check('访问计数器与吉祥物不充当核心图',!('coreImg' in w.repos.find(r=>r.full_name==='AprilNEA/OpenLogi'))&&!('coreImg' in w.repos.find(r=>r.full_name==='MadsLorentzen/ai-job-search')));
 check('GitHub attachment 保持原地址',coreImage('![Screenshot](https://github.com/user-attachments/assets/example)','a/b')==='https://github.com/user-attachments/assets/example');
 check('图优先级、HTML entity 与相对地址',coreImage('![photo](first.png)<img src="./docs/hero.png?a=1&amp;b=2" alt="preview">','a/b')==='https://raw.githubusercontent.com/a/b/HEAD/docs/hero.png?a=1&b=2');
 check('注释/code/logo/shields/危险协议不作为核心图',coreImage('<!-- ![hero](bad.png) -->\n'+String.fromCharCode(96).repeat(3)+'\n![hero](code.png)\n'+String.fromCharCode(96).repeat(3)+'\n![logo](logo.png) ![badge](https://img.shields.io/x) ![x](javascript:alert) ','a/b')===undefined);
 const old=JSON.parse(readFileSync(join(fixtures,'old-week','2026-W28.json'),'utf8'));writeDoc(old);
 copyFileSync(join(fixtures,'old-week','legacy.analysis.md'),join(weeks,'2026-W28.analysis.md'));
 const oldPayload=buildPayload(weeks).weeks[0];
 check('旧周无新注释/无过期误报、整篇旧分析保留',oldPayload.repos.every(r=>!r.note)&&!('staleAt' in oldPayload)&&oldPayload.analysis.length>0);
 check('未知 tag 拒绝结构化注释',extractNotes(analysis.replaceAll('"agent-skills"','"uncontrolled-tag"')).size<20);
 check('readme-cap 超上限夹到2400',buildPayload(weeks,{readmeCap:9999}).weeks.at(-1).repos[0].readme.length===2400);
 const backfill=join(ws,'backfill');mkdirSync(backfill);
 writeFileSync(join(backfill,'2026-W35.presence.json'),JSON.stringify({week:'2026-W35',repos:[{full_name:'tt-a1i/archify',days_on_list:4,best_rank:1}]}));
 check('presence 有则透传且旧周不借未来数据',buildPayload(weeks).weeks.at(-1).repos[0].presence.days===4&&!buildPayload(weeks).weeks[0].repos.some(r=>r.presence));
 console.log('== T13/AC-006 stale 咬合 + 历史时序 ==');
 const changed=structuredClone(golden);changed.repos[0].entry_status='new';writeDoc(changed);
 const legacy='## 旧分析：新晋20\n';writeFileSync(join(weeks,'2026-W36.analysis.md'),legacy);
 const r1=run('update-history.mjs',['--workspace',ws,'--week','2026-W36']);
 const stale=JSON.parse(readFileSync(join(weeks,'2026-W36.json'),'utf8'));
 check('重分类写 staleAt/staleReason，旧分析 hash 固定',r1.status===0&&stale.staleAt&&stale.staleReason.includes('new→returning')&&stale.staleAnalysisHash);
 check('build-report stale 透传',buildPayload(weeks).weeks.at(-1).staleAt===stale.staleAt);
 run('update-history.mjs',['--workspace',ws,'--week','2026-W36']);
 check('同分析重跑不解除 stale',JSON.parse(readFileSync(join(weeks,'2026-W36.json'),'utf8')).staleAt===stale.staleAt);
 writeFileSync(join(weeks,'2026-W36.analysis.md'),legacy+'文字修饰');
 check('只改文字不清除过期标记',!!buildPayload(weeks).weeks.at(-1).staleAt);
 writeFileSync(join(weeks,'2026-W36.analysis.md'),'<!-- entry-status: '+JSON.stringify(classification(stale.repos))+' -->\n'+analysis.replace(/<!--.*?-->/,''));
 check('重写且分类吻合即解除 viewer 黄条',!buildPayload(weeks).weeks.at(-1).staleAt);
 run('update-history.mjs',['--workspace',ws,'--week','2026-W36']);
 check('update-history 清除已刷新 stale 元数据',!JSON.parse(readFileSync(join(weeks,'2026-W36.json'),'utf8')).staleAt);
 // A historical rerun must not see a later snapshot as a previous appearance.
 run('update-history.mjs',['--workspace',ws,'--week','2026-W28']);
 const rerun=JSON.parse(readFileSync(join(weeks,'2026-W28.json'),'utf8'));
 check('回填旧周不拿未来分类/环比',rerun.repos.find(r=>r.full_name==='tt-a1i/archify').entry_status==='new');
 check('回跑旧周保留 last_seen_week',JSON.parse(readFileSync(join(repos,'tt-a1i__archify.json'),'utf8')).last_seen_week==='2026-W36');
 console.log('== T14/AC-006 enrich 五信源 ==');
 const enriched=run('enrich-repos.mjs',['--workspace',ws,'--week','2026-W36','--stub',join(fixtures,'stub')]);
 const doc=JSON.parse(readFileSync(join(weeks,'2026-W36.json'),'utf8')),arch=doc.repos[0],google=doc.repos.find(r=>r.full_name==='google/googletest');
 check('5 标记齐全',enriched.status===0&&enriched.out.includes('+readme +tree +contrib +commit +release'));
 check('tree/contrib/commit/release 结构正确',arch.tree.some(t=>t.path==='scripts')&&arch.contributors.length<=20&&arch.commits_90d.items.length>0&&arch.releases.length<=3);
 check('单信源403不整仓失败',google.api_ok===true&&google.source_status.contrib===false&&!('contributors' in google)&&google.readme_excerpt.length>0);
 check('缺元数据仓保持 api_ok:false',doc.repos[1].api_ok===false);
 check('五信源产物过校验',validateWeek(doc).length===0);
 const invalid=structuredClone(doc);invalid.repos[0].tree='bad';invalid.staleAt='not-date';
 check('新可选字段出现即校验',validateWeek(invalid).some(e=>e.includes('tree'))&&validateWeek(invalid).some(e=>e.includes('staleAt')));
 check('正常重建成功且没有新增应用依赖',run('build-report.mjs',['--workspace',ws]).status===0&&!existsSync(join(fixtures,'..','package.json')));
}
